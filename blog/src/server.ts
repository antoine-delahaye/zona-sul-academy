import { AngularAppEngine, createRequestHandler } from '@angular/ssr';

import { NOT_FOUND_PATH, matchesRoute } from './app/app.routes';
import { ContactEnv, handleContactRequest } from './contact.endpoint';
import { CONTACT_ENDPOINT } from './shared/contact/contact.model';
import { SANITY_API_HOST, SANITY_IMAGE_CDN_URL } from './data/sanity.config';
import { TURNSTILE_ORIGIN } from './shared/turnstile/turnstile.config';

const angularApp = new AngularAppEngine();

const SANITY_API_ORIGIN = `https://${SANITY_API_HOST}`;

/** Hosts pulled in by `@angular/youtube-player` when a video section is present. */
const YOUTUBE_API_ORIGIN = 'https://www.youtube.com';
const YOUTUBE_PLAYER_ORIGIN = 'https://www.youtube-nocookie.com';
const YOUTUBE_SCRIPT_ORIGIN = 'https://s.ytimg.com';
const YOUTUBE_THUMBNAIL_ORIGIN = 'https://i.ytimg.com';

/**
 * `'unsafe-inline'` is still required for scripts and styles: Angular emits
 * inline hydration/transfer-state scripts and injects component styles as inline
 * `<style>` blocks. Tightening this means switching to the builder's hash-based
 * `security.autoCsp` option, which is still in preview.
 *
 * `TURNSTILE_ORIGIN` appears three times over because the anti-robot widget on
 * the contact page loads a script, mounts an iframe, and reports its outcome back
 * to Cloudflare.
 */
const CONTENT_SECURITY_POLICY = [
  `default-src 'self'`,
  `base-uri 'self'`,
  `object-src 'none'`,
  `form-action 'self'`,
  `frame-ancestors 'none'`,
  `script-src 'self' 'unsafe-inline' ${TURNSTILE_ORIGIN} ${YOUTUBE_API_ORIGIN} ${YOUTUBE_SCRIPT_ORIGIN}`,
  `style-src 'self' 'unsafe-inline'`,
  `img-src 'self' data: ${SANITY_IMAGE_CDN_URL} ${YOUTUBE_THUMBNAIL_ORIGIN}`,
  `font-src 'self'`,
  `connect-src 'self' ${SANITY_API_ORIGIN} ${TURNSTILE_ORIGIN}`,
  `frame-src ${TURNSTILE_ORIGIN} ${YOUTUBE_PLAYER_ORIGIN} ${YOUTUBE_API_ORIGIN}`,
  `upgrade-insecure-requests`,
].join('; ');

/**
 * Security headers for every response this Worker produces.
 *
 * `public/_headers` only covers responses served straight from static assets:
 * Cloudflare does not apply it to responses generated by Worker code, and with
 * SSR that is every HTML page on the site.
 */
const SECURITY_HEADERS: Readonly<Record<string, string>> = {
  'Content-Security-Policy': CONTENT_SECURITY_POLICY,
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains; preload',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Permissions-Policy': [
    'accelerometer=()',
    'camera=()',
    'geolocation=()',
    'gyroscope=()',
    'magnetometer=()',
    'microphone=()',
    'payment=()',
    'usb=()',
  ].join(', '),
};

/** Response headers are immutable, so the response is rebuilt around a new set. */
function withSecurityHeaders(response: Response, requestUrl: string): Response {
  const headers = new Headers(response.headers);

  for (const [name, value] of Object.entries(SECURITY_HEADERS)) {
    headers.set(name, value);
  }

  // Keep the deploy preview out of search results. This cannot live in
  // `_headers` either, for the same reason the security headers cannot.
  if (new URL(requestUrl).hostname.endsWith('.workers.dev')) {
    headers.set('X-Robots-Tag', 'noindex');
  }

  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

/**
 * Minimal shape of the static assets binding declared in `wrangler.jsonc`, typed
 * here for the same reason as `SendEmailBinding` in `contact.endpoint.ts`.
 */
interface AssetsBinding {
  fetch(request: Request): Promise<Response>;
}

interface WorkerEnv extends ContactEnv {
  /** Absent under `ng serve`, which runs the SSR entry outside workerd. */
  readonly ASSETS?: AssetsBinding;
}

/**
 * Answers a URL no route matches with the not-found page prerendered at build
 * time, without starting Angular.
 *
 * Rendering costs a few hundred milliseconds of CPU whatever the page, against
 * 10 on the Workers free plan. Vulnerability scanners probing `/wp-login.php`,
 * `/.env` and the like in bursts got the Worker cut off, which failed real
 * visitors' requests in the same burst too.
 *
 * @returns `undefined` when the static copy cannot be read, notably under
 *   `ng serve`, so that Angular renders the page instead.
 */
async function serveNotFoundPage(request: Request, env?: WorkerEnv): Promise<Response | undefined> {
  if (!env?.ASSETS) {
    return undefined;
  }

  const page = await env.ASSETS.fetch(new Request(new URL(`/${NOT_FOUND_PATH}/`, request.url)));

  if (!page.ok) {
    return undefined;
  }

  return new Response(page.body, { status: 404, headers: page.headers });
}

/**
 * The single path through the Worker, whichever entry point called it.
 *
 * @param env Cloudflare bindings and secrets. Only the default export receives
 *   them: `reqHandler` is called by the Angular dev server with the request
 *   alone, so the contact endpoint answers 503 under `ng serve`.
 */
async function handle(request: Request, env?: WorkerEnv): Promise<Response> {
  const { pathname } = new URL(request.url);

  // Intercepted before Angular, which would otherwise render the 404 page for it.
  if (pathname === CONTACT_ENDPOINT) {
    return withSecurityHeaders(await handleContactRequest(request, env), request.url);
  }

  if (!matchesRoute(pathname)) {
    const notFound = await serveNotFoundPage(request, env);

    if (notFound) {
      return withSecurityHeaders(notFound, request.url);
    }
  }

  const response = await angularApp.handle(request);

  return withSecurityHeaders(
    response ?? new Response('Page not found.', { status: 404 }),
    request.url,
  );
}

/** Used by the Angular dev server, which looks this export up by name. */
export const reqHandler = createRequestHandler((request) => handle(request));

/**
 * Used by workerd. Declared separately from `reqHandler` because Angular's
 * `RequestHandlerFunction` takes only a request, and the contact endpoint needs
 * the `env` argument the runtime passes alongside it.
 */
export default {
  fetch: (request: Request, env: WorkerEnv): Promise<Response> => handle(request, env),
};
